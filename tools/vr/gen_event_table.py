#!/usr/bin/env python3
"""Writes runtime/vr/vr_event_table.h, the per-event first-person settings, from BetterVR's
resources/BreathOfTheWild_BetterVR/patch_Settings_Cutscenes.asm (BotW-BetterVR, Crementif and contributors, MIT).
Each `.string "<event>,FP_ON|FP_OFF,PAN_ON|PAN_OFF,HND_ON|HND_OFF,CTRL_ON|CTRL_OFF"` becomes one entry, sorted by name.

  python tools/vr/gen_event_table.py <BotW-BetterVR checkout>
"""
import os
import re
import sys

src = os.path.join(sys.argv[1], 'resources', 'BreathOfTheWild_BetterVR', 'patch_Settings_Cutscenes.asm')
rows = {}
for line in open(src, encoding='utf-8', errors='replace'):
    m = re.match(r'\s*\.string\s+"([^"]+)"', line)
    if not m:
        continue
    parts = m.group(1).split(',')
    name, flags = parts[0], set(parts[1:])
    if not name or not re.fullmatch(r'[\w.-]+', name):
        continue
    rows[name] = ('FP_ON' in flags, 'PAN_OFF' in flags, 'HND_OFF' in flags)
out = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', 'runtime', 'vr', 'vr_event_table.h')
with open(out, 'w', encoding='utf-8', newline='\n') as f:
    f.write('// Generated by tools/vr/gen_event_table.py from BotW-BetterVR\'s patch_Settings_Cutscenes.asm (Crementif and\n'
            '// contributors, MIT License): per event (or event flow) name, whether BetterVR shows it in first person\n'
            '// (fp), keeps the view from following the event camera\'s turns (still: PAN_OFF) and leaves Link\'s hands to\n'
            '// the animation (anim_hands: HND_OFF). Sorted by name (strcmp) for a binary search.\n'
            '#pragma once\n#include <stdbool.h>\n\n'
            'typedef struct { const char *name; bool fp, still, anim_hands; } vr_event_setting;\n\n'
            'static const vr_event_setting vr_event_table[] = {\n')
    for name in sorted(rows, key=lambda s: s.encode()):
        fp, still, hands = rows[name]
        f.write('    {"%s", %d, %d, %d},\n' % (name, fp, still, hands))
    f.write('};\n')
print(len(rows), 'events ->', os.path.normpath(out))
